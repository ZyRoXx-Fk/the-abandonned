import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildMcpTestApp } from './helpers/mcp-app.js';
const owner = { role: 'owner' as const, userId: 'owner1' };
const customer = { role: 'client' as const, userId: 'client1' };
test('real SDK transports isolate identities, reject foreign IDs and reconnect unpaired across aliases', async t => {
  const h = await buildMcpTestApp(); t.after(() => h.close());
  const a = await h.connect(); const b = await h.connect('/sse');
  assert.notEqual(a.transport.sessionId, b.transport.sessionId);
  const code = await h.pairing.generateForPrincipal(owner);
  const foreign = await b.client.callTool({ name: 'pair_session', arguments: { token: code.token, sessionId: a.transport.sessionId } });
  assert.equal(foreign.isError, true);
  const paired = await a.client.callTool({ name: 'pair_session', arguments: { token: code.token } });
  assert.notEqual(paired.isError, true);
  assert.deepEqual(h.sessions.requirePrincipal(a.transport.sessionId!), owner);
  assert.throws(() => h.sessions.requirePrincipal(b.transport.sessionId!));
  assert.throws(() => h.sessions.requirePrincipal(a.transport.sessionId!, 'client'));
  const second = await h.pairing.generateForPrincipal(customer);
  assert.equal((await a.client.callTool({ name: 'pair_session', arguments: { token: second.token } })).isError, true);
  assert.notEqual((await b.client.callTool({ name: 'pair_session', arguments: { token: second.token } })).isError, true);
  const tools = await a.client.listTools();
  assert.deepEqual(tools.tools.map(x => x.name), ['pair_session']);
  const status = await (await fetch(h.base + '/mcp/status')).json();
  assert.deepEqual(Object.keys(status).sort(), ['activeSessions', 'status']);
  const id = a.transport.sessionId!;
  await a.transport.terminateSession();
  assert.throws(() => h.sessions.requirePrincipal(id));
  const c = await h.connect('/messages');
  assert.throws(() => h.sessions.requirePrincipal(c.transport.sessionId!));
  const dead = await fetch(h.base + '/mcp', { method: 'POST', headers: { 'content-type': 'application/json', 'mcp-session-id': id }, body: JSON.stringify({ jsonrpc: '2.0', id: 9, method: 'ping' }) });
  assert.equal(dead.status, 404);
});
test('pairing concurrency, dead/unknown sessions and expiry never burn usable codes', async t => {
  let time = Date.now(); const h = await buildMcpTestApp(() => new Date(time)); t.after(() => h.close());
  const a = await h.connect(); const b = await h.connect();
  const code = await h.pairing.generateForPrincipal(owner);
  await assert.rejects(h.pairing.consumeForSession(code.token, 'unknown'));
  const result = await Promise.allSettled([h.pairing.consumeForSession(code.token, a.transport.sessionId!), h.pairing.consumeForSession(code.token, b.transport.sessionId!)]);
  assert.equal(result.filter(x => x.status === 'fulfilled').length, 1);
  const replacement = await h.pairing.generateForPrincipal(customer);
  const pendingSession = result[0].status === 'fulfilled' ? b.transport.sessionId! : a.transport.sessionId!;
  const consume = h.tokens.consume.bind(h.tokens);
  h.tokens.consume = async (...args) => { const p = await consume(...args); h.sessions.removeSession(pendingSession); return p; };
  await assert.rejects(h.pairing.consumeForSession(replacement.token, pendingSession));
  h.tokens.consume = consume;
  const c = await h.connect();
  await h.pairing.consumeForSession(replacement.token, c.transport.sessionId!);
  time += 30 * 60000;
  await h.service.cleanup();
  assert.equal(h.sessions.getActiveCount(), 0);
  assert.throws(() => h.sessions.requirePrincipal(c.transport.sessionId!));
});
test('failure limits are session and server-derived IP scoped; clock expires codes', async t => {
  let time = Date.now(); const h = await buildMcpTestApp(() => new Date(time)); t.after(() => h.close());
  for (let i = 0; i < 3; i++) {
    const a = await h.connect();
    for (let j = 0; j < 10; j++) assert.equal((await a.client.callTool({ name: 'pair_session', arguments: { token: 'bad' } })).isError, true);
    const code = await h.pairing.generateForPrincipal(owner);
    assert.equal((await a.client.callTool({ name: 'pair_session', arguments: { token: code.token } })).isError, true);
  }
  const b = await h.connect(); const code = await h.pairing.generateForPrincipal(owner);
  const limited = await b.client.callTool({ name: 'pair_session', arguments: { token: code.token } });
  assert.equal(limited.isError, true);
  assert.match(JSON.stringify(limited), /Too many/);
  time += 60001;
  assert.notEqual((await b.client.callTool({ name: 'pair_session', arguments: { token: code.token } })).isError, true);
  const expired = await h.pairing.generateForPrincipal(customer);
  const c = await h.connect(); time += 15 * 60000;
  await assert.rejects(h.pairing.consumeForSession(expired.token, c.transport.sessionId!));
});

test('accepted SDK GET disconnect invalidates; rejected duplicate GET and POST do not; shutdown removes all', async t => {
  const h = await buildMcpTestApp(); t.after(() => h.close());
  const a = await h.connect(); const id = a.transport.sessionId!;
  const code = await h.pairing.generateForPrincipal(owner);
  await h.pairing.consumeForSession(code.token, id);
  const duplicate = await fetch(h.base + '/mcp', { headers: { accept: 'text/event-stream', 'mcp-session-id': id } });
  assert.equal(duplicate.status, 409);
  await duplicate.text();
  const rejected = await fetch(h.base + '/mcp', { headers: { accept: 'application/json', 'mcp-session-id': id }, signal: AbortSignal.timeout(2000) });
  assert.equal(rejected.status, 406);
  await rejected.text();
  assert.deepEqual(h.sessions.requirePrincipal(id), owner);
  await a.client.ping();
  assert.deepEqual(h.sessions.requirePrincipal(id), owner);
  // Observe the actual transport close instead of sleeping for an arbitrary network interval.
  let removed!: () => void;
  const disconnected = new Promise<void>(resolve => { removed = resolve; });
  const remove = h.sessions.removeSession.bind(h.sessions);
  h.sessions.removeSession = sessionId => { remove(sessionId); if (sessionId === id) removed(); };
  await a.client.close(); await disconnected;
  assert.throws(() => h.sessions.requirePrincipal(id));
  const old = await fetch(h.base + '/mcp', { signal: AbortSignal.timeout(2000), headers: { accept: 'text/event-stream', 'mcp-session-id': id } });
  assert.equal(old.status, 404);
  const b = await h.connect();
  assert.notEqual(b.transport.sessionId, id);
  assert.throws(() => h.sessions.requirePrincipal(b.transport.sessionId!));
  await h.app.close();
  assert.equal(h.sessions.getActiveCount(), 0);
});
